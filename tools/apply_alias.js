function main() {
  const check = process.argv.indexOf("--check") !== -1;
  let missing = [], total = 0;
  Object.keys(ALIAS).forEach((file) => {
    const p = path.join(DATA_DIR, file + ".json");
    const raw = fs.readFileSync(p, "utf8");
    const data = JSON.parse(raw);
    const map = ALIAS[file];
    data.items.forEach((it) => {
      const kw = map[it.id];
      if (!kw) { missing.push(file + "/" + it.id); return; }
      total++;
      if (!check) it.kw = kw;
    });
    if (!check) fs.writeFileSync(p, JSON.stringify(data, null, 2) + "\n", "utf8");
  });
  if (missing.length) {
    console.log("✗ 缺别名：" + missing.join(", "));
    process.exit(1);
  }
  console.log((check ? "别名体检通过：" : "别名已写入：") + total + " 条");
}
main();
