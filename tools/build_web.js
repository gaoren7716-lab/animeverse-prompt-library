#!/usr/bin/env node
/* 把 data/*.json 打包成 assets/data-bundle.js（浏览器 file:// 直接可开）。
 * 派生物，不要手改 —— 改数据后重跑本脚本。 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const FILES = [
  "regions", "styles", "media", "subjects", "characters",
  "worlds", "shots", "lights", "layouts", "sizes", "decors",
  "series", "cases", "conflicts", "templates", "palettes", "entities",
];

function main() {
  const out = {};
  const counts = [];
  for (const name of FILES) {
    const p = path.join(ROOT, "data", name + ".json");
    out[name] = JSON.parse(fs.readFileSync(p, "utf8"));
    const n = out[name].items ? out[name].items.length
      : out[name].conflicts ? out[name].conflicts.length
      : out[name].entities ? out[name].entities.length : 0;
    counts.push(name + "=" + n);
  }
  const js =
    "/* GENERATED by tools/build_web.js — DO NOT EDIT BY HAND */\n" +
    "window.AV_DATA = " + JSON.stringify(out, null, 2) + ";\n";
  fs.writeFileSync(path.join(ROOT, "assets", "data-bundle.js"), js, "utf8");

  // 引擎原样复制到 assets/engine.js（UMD：浏览器读 window.AV_DATA，Node 读 data/*.json）
  const engine = fs.readFileSync(path.join(ROOT, "tools", "compose.js"), "utf8");
  fs.writeFileSync(path.join(ROOT, "assets", "engine.js"), engine, "utf8");

  console.log("data-bundle.js 已重建：" + counts.join(" "));
  console.log("engine.js 已同步（tools/compose.js 的副本，勿手改）");
}

if (require.main === module) main();
module.exports = { main };
