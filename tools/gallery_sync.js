#!/usr/bin/env node
/* 画廊同步（轻量版，吸收 art-prompt-forge / ecommerce 画廊约定）：
 * gallery/ 目录里，文件名主干 = 画廊槽位 id，扩展名不限格式
 *（CS-01.png / CS-01.jpg / GL-23.webp 都认），扫一次目录重写
 * assets/gallery-imgs.js（派生物，勿手改）。
 * 野文件名（认不出的 id）进 GALLERY_UNCLAIMED，页面上出提示条。
 * --check 只体检：有未认领文件或清单与目录不一致 → 退出码 1。
 * 注：本库画廊是「实测出图落点」，没有图时清单为空、页面如实显示 0 张。
 * 槽位表在 data/gallery.json（50 个位置），案例表在 data/cases.json（10 条验证案例），
 * 两者 id 空间不同：CS-xx 已在 cases.json 登记，GL-xx 在 gallery.json 登记。 */
"use strict";
const fs = require("fs");
const path = require("path");
const { q, readVer } = require("./asset_ver.js");

const ROOT = path.join(__dirname, "..");
const GAL = path.join(ROOT, "gallery");
const OUT = path.join(ROOT, "assets", "gallery-imgs.js");

/* 清单里的图片路径统一拼 ?v=<资产版本号>：
 * 同名文件内容变了（压缩重跑、换图同格式）URL 也必须变，否则浏览器拿缓存旧字节——
 * 「本地明明更新了，线上/刷新就是不换」的第二轮根因就是缺这一层。
 * 版本号由 tools/asset_ver.js 管理，gallery_refresh 先 bump 再 sync。 */
function imgPath(rel) { return q(readVer(), rel); }

/* 支持的图片格式（大小写不敏感）。新增格式只改这一处。 */
const IMAGE_EXT = ["png", "jpg", "jpeg", "webp"];
const EXT_RE = new RegExp("^([A-Z]{2}-\\d{2})\\.(" + IMAGE_EXT.join("|") + ")$", "i");

function knownIds() {
  const ids = {};
  // 案例 id（CS-xx）——画廊前 10 位复用案例
  JSON.parse(fs.readFileSync(path.join(ROOT, "data", "cases.json"), "utf8"))
    .items.forEach(it => { ids[it.id] = it.zh; });
  // 画廊槽位 id（GL-xx / CS-xx）——预留位
  const gal = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "gallery.json"), "utf8"));
  gal.slots.forEach(s => { ids[s.id] = s.zh || (s.case ? s.case : s.id); });
  return ids;
}

function readManifest() {
  if (!fs.existsSync(OUT)) return null;
  const src = fs.readFileSync(OUT, "utf8");
  const m = src.match(/window\.GALLERY_IMGS\s*=\s*([\s\S]*?);/);
  if (!m) return null;
  try { return JSON.parse(m[1]); } catch (e) { return null; }
}

/* 扫描目录：按 id 归组，同 id 多格式取 mtime 较新的一张，其余记为 dup。
 * 抽成独立函数便于测试（不碰真实 gallery/ 目录）。 */
function scanDir(dir, ids) {
  const byId = {};
  const unclaimed = [];
  let names = [];
  try { names = fs.readdirSync(dir); } catch (e) { return { claimed: {}, unclaimed: [], dups: [] }; }
  for (const f of names) {
    if (f.startsWith("_") || f.startsWith(".")) continue; // 母版/临时产物
    const m = f.match(EXT_RE);
    if (!m) { unclaimed.push(f); continue; }
    const id = m[1].toUpperCase();          // 文件名主干归一化：cs-01.png 也认
    if (!ids[id]) { unclaimed.push(f); continue; }
    const st = fs.statSync(path.join(dir, f));
    (byId[id] = byId[id] || []).push({ file: f, mtime: st.mtimeMs });
  }
  const claimed = {};
  const dups = [];
  Object.keys(byId).sort().forEach(id => {
    const list = byId[id].sort((a, b) => b.mtime - a.mtime);
    claimed[id] = "gallery/" + list[0].file;
    list.slice(1).forEach(x => dups.push({ id: id, file: x.file, keep: list[0].file }));
  });
  return { claimed, unclaimed, dups };
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const ids = knownIds();
  if (!fs.existsSync(GAL)) fs.mkdirSync(GAL, { recursive: true });

  /* 先按 id 归组：同一 id 允许多种格式并存（用户可能重出图换了格式）。
   * 归组后按 mtime 倒序取最新那张，其余记为 dup 报警——
   * 早期版本是 readdir 顺序直接覆盖，同 id 两格式时清单会随机指向哪张，不确定。 */
  const scan = scanDir(GAL, ids);
  const unclaimed = scan.unclaimed, dups = scan.dups;
  // 扫描层出纯路径；发布层（写清单 / 体检比对）才拼 ?v= 版本号。
  // 分开的原因：scanDir 是纯目录逻辑，被多格式测试直接调用，
  // 在扫描层拼版本会让测试断言全带 query，也混淆了职责。
  const claimed = {};
  Object.keys(scan.claimed).forEach(id => { claimed[id] = imgPath(scan.claimed[id]); });

  const js =
    "/* GENERATED by tools/gallery_sync.js — DO NOT EDIT BY HAND */\n" +
    "window.GALLERY_IMGS = " + JSON.stringify(claimed, null, 2) + ";\n" +
    "window.GALLERY_UNCLAIMED = " + JSON.stringify(unclaimed, null, 2) + ";\n";
  if (!checkOnly) fs.writeFileSync(OUT, js, "utf8");

  const n = Object.keys(claimed).length;
  console.log("画廊：认领 " + n + " 张" + (checkOnly ? "（--check 不写清单）" : "，清单已重建"));
  unclaimed.forEach(f => console.log("  ⚠ 未认领（文件名须是槽位 id，如 CS-01.png 或 CS-01.jpg）：" + f));
  dups.forEach(d => console.log("  ⚠ 同一槽位有多个文件 " + d.id + "：采用较新的 " + d.keep +
    "，未采用 " + d.file + "（请删掉多余的，避免下次同步时又换一张）"));

  if (checkOnly) {
    // 清单与目录逐张对比（注释承诺过的事必须真做）：
    // 重出图期间清单是 .jpg、磁盘已是 .png 这类漂移，以前发现不了，页面直接碎图。
    let bad = unclaimed.length > 0 || dups.length > 0;
    const old = readManifest();
    if (!old) { console.log("  ✗ 清单缺失或无法解析：" + OUT); bad = true; }
    else {
      const keys = Array.from(new Set(Object.keys(old).concat(Object.keys(claimed))));
      keys.forEach(k => {
        if (old[k] !== claimed[k]) {
          bad = true;
          console.log("  ✗ 清单与目录不一致 " + k + "：清单 " + (old[k] || "（无）") +
            " / 磁盘 " + (claimed[k] || "（无）") + " —— 重跑 gallery_sync.js 重建清单");
        }
      });
    }
    if (bad) { console.log("画廊体检异常"); process.exit(1); }
    console.log("画廊体检通过：清单与目录一致");
    return;
  }
}

if (require.main === module) main();
module.exports = { main, IMAGE_EXT, scanDir, knownIds };
