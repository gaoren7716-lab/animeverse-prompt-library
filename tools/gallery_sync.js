#!/usr/bin/env node
/* 画廊同步（轻量版，吸收 art-prompt-forge / ecommerce 画廊约定）：
 * gallery/ 目录里，文件名主干 = 画廊槽位 id（CS-01.jpg / GL-23.png），
 * 扫一次目录重写 assets/gallery-imgs.js（派生物，勿手改）。
 * 野文件名（认不出的 id）进 GALLERY_UNCLAIMED，页面上出提示条。
 * --check 只体检：有未认领文件或清单与目录不一致 → 退出码 1。
 * 注：本库画廊是「实测出图落点」，没有图时清单为空、页面如实显示 0 张。
 * 槽位表在 data/gallery.json（50 个位置），案例表在 data/cases.json（10 条验证案例），
 * 两者 id 空间不同：CS-xx 已在 cases.json 登记，GL-xx 在 gallery.json 登记。 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const GAL = path.join(ROOT, "gallery");
const OUT = path.join(ROOT, "assets", "gallery-imgs.js");

function knownIds() {
  const ids = {};
  // 案例 id（CS-xx）——画廊前 10 位复用案例
  JSON.parse(fs.readFileSync(path.join(ROOT, "data", "cases.json"), "utf8"))
    .items.forEach(it => { ids[it.id] = it.zh; });
  // 画廊槽位 id（GL-xx / CS-xx）——预留位
  const gal = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "gallery.json"), "utf8"));
  gal.slots.forEach(s => { ids[s.id] = s.zh || (s.case ? s.case : s.id); });
  return ids;
}

function readManifest() {
  if (!fs.existsSync(OUT)) return null;
  const src = fs.readFileSync(OUT, "utf8");
  const m = src.match(/window\.GALLERY_IMGS\s*=\s*([\s\S]*?);/);
  if (!m) return null;
  try { return JSON.parse(m[1]); } catch (e) { return null; }
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const ids = knownIds();
  if (!fs.existsSync(GAL)) fs.mkdirSync(GAL, { recursive: true });

  const claimed = {}, unclaimed = [];
  for (const f of fs.readdirSync(GAL)) {
    if (f.startsWith("_") || f.startsWith(".")) continue; // 母版/临时产物
    const m = f.match(/^([A-Z]{2}-\d{2})\.(png|jpe?g|webp)$/i);
    if (m && ids[m[1]]) claimed[m[1]] = "gallery/" + f;
    else unclaimed.push(f);
  }

  const js =
    "/* GENERATED by tools/gallery_sync.js — DO NOT EDIT BY HAND */\n" +
    "window.GALLERY_IMGS = " + JSON.stringify(claimed, null, 2) + ";\n" +
    "window.GALLERY_UNCLAIMED = " + JSON.stringify(unclaimed, null, 2) + ";\n";
  if (!checkOnly) fs.writeFileSync(OUT, js, "utf8");

  const n = Object.keys(claimed).length;
  console.log("画廊：认领 " + n + " 张" + (checkOnly ? "（--check 不写清单）" : "，清单已重建"));
  unclaimed.forEach(f => console.log("  ⚠ 未认领（文件名须是槽位 id，如 CS-01.jpg 或 GL-23.jpg）：" + f));

  if (checkOnly) {
    // 清单与目录逐张对比（注释承诺过的事必须真做）：
    // 重出图期间清单是 .jpg、磁盘已是 .png 这类漂移，以前发现不了，页面直接碎图。
    let bad = unclaimed.length > 0;
    const old = readManifest();
    if (!old) { console.log("  ✗ 清单缺失或无法解析：" + OUT); bad = true; }
    else {
      const keys = Array.from(new Set(Object.keys(old).concat(Object.keys(claimed))));
      keys.forEach(k => {
        if (old[k] !== claimed[k]) {
          bad = true;
          console.log("  ✗ 清单与目录不一致 " + k + "：清单 " + (old[k] || "（无）") +
            " / 磁盘 " + (claimed[k] || "（无）") + " —— 重跑 gallery_sync.js 重建清单");
        }
      });
    }
    if (bad) { console.log("画廊体检异常"); process.exit(1); }
    console.log("画廊体检通过：清单与目录一致");
    return;
  }
}

if (require.main === module) main();
module.exports = { main };
